create table public.menu_item_ingredients (
  menu_item_id int  not null references public.menu_items (id) on delete cascade,
  category     text not null check (category in ('beef', 'poultry', 'fish', 'veg')),
  ingredient   text not null check (length(trim(ingredient)) > 0),
  grams        int  not null check (grams > 0),
  primary key (menu_item_id, category, ingredient)
);

-- הרשאות: כמו menu_items. כולם קוראים, השף ומנהל כללי עורכים.
-- ה-grant ב-0001 חל רק על טבלאות שהיו קיימות אז, ולכן נותנים כאן במפורש
alter table public.menu_item_ingredients enable row level security;
grant select on public.menu_item_ingredients to anon, authenticated;
grant insert, update, delete on public.menu_item_ingredients to authenticated;
grant all on public.menu_item_ingredients to service_role;

create policy ingredients_select on public.menu_item_ingredients for select to anon, authenticated using (true);
create policy ingredients_write on public.menu_item_ingredients for all to authenticated
  using (public.app_role() in ('chef', 'admin')) with check (public.app_role() in ('chef', 'admin'));

